"""Generate g1_grasp.urdf: HOMIE's g1.urdf with the Dex3 grasp baked into the fixed finger joints.

Only the ``rpy`` attribute of the 14 fixed finger joints changes. Every movable
joint, link, inertial, limit, and mesh reference stays identical, so the 27-DoF
articulation seen by the HOMIE policy is unchanged.
"""
from __future__ import annotations

import re
import xml.etree.ElementTree as ET

import numpy as np
from scipy.spatial.transform import Rotation as R

from ..paths import FINGER_JOINTS, G1_GRASP_URDF, G1_URDF

_JOINT_BLOCK = re.compile(r'<joint name="(?P<name>[^"]+)" type="fixed">.*?</joint>', re.S)
_ORIGIN = re.compile(r'<origin xyz="(?P<xyz>[^"]*)" rpy="(?P<rpy>[^"]*)"\s*/>')
_AXIS = re.compile(r'<axis xyz="(?P<xyz>[^"]*)"\s*/>')


def _fmt(values):
    return " ".join(f"{v:.8g}" if abs(v) > 1e-12 else "0" for v in values)


def bake_rpy(rpy: np.ndarray, axis: np.ndarray, angle: float) -> np.ndarray:
    """URDF rpy is extrinsic x-y-z. The joint rotation acts after the origin frame."""
    base = R.from_euler("xyz", rpy)
    joint = R.from_rotvec(np.asarray(axis, dtype=float) / np.linalg.norm(axis) * angle)
    return (base * joint).as_euler("xyz")


def build_g1_grasp_urdf(finger_angles: dict[str, float], source=G1_URDF, destination=G1_GRASP_URDF) -> dict:
    text = source.read_text(encoding="utf-8")
    missing = [name for name in FINGER_JOINTS if name not in finger_angles]
    if missing:
        raise KeyError(f"finger angles missing: {missing}")
    report = {}

    def replace_block(match: re.Match) -> str:
        name = match.group("name")
        if name not in finger_angles:
            return match.group(0)
        block = match.group(0)
        origin = _ORIGIN.search(block)
        axis = _AXIS.search(block)
        if origin is None or axis is None:
            raise ValueError(f"{name}: fixed finger joint lacks origin or axis")
        rpy = np.array([float(v) for v in origin.group("rpy").split()])
        axis_xyz = np.array([float(v) for v in axis.group("xyz").split()])
        new_rpy = bake_rpy(rpy, axis_xyz, float(finger_angles[name]))
        report[name] = {"angle": float(finger_angles[name]), "axis": axis_xyz.tolist(),
                        "rpy_before": rpy.tolist(), "rpy_after": new_rpy.tolist()}
        new_origin = f'<origin xyz="{origin.group("xyz")}" rpy="{_fmt(new_rpy)}"/>'
        return block.replace(origin.group(0), new_origin, 1)

    new_text = _JOINT_BLOCK.sub(replace_block, text)
    if len(report) != len(FINGER_JOINTS):
        raise ValueError(f"expected {len(FINGER_JOINTS)} finger joints, baked {len(report)}")
    comment = ("<!-- Generated by homie_pushcart.assets.g1_grasp_urdf from g1.urdf: Dex3 grasp angles baked into the "
               "14 fixed finger joints. Movable joints, links, inertials, limits, and meshes are identical. -->\n")
    new_text = re.sub(r"(<robot[^>]*>\n)", lambda m: m.group(1) + comment, new_text, count=1)
    destination.write_text(new_text, encoding="utf-8")
    verify_g1_grasp_urdf(source, destination)
    return report


def verify_g1_grasp_urdf(source=G1_URDF, destination=G1_GRASP_URDF) -> None:
    """Everything except the 14 finger-joint rpy values must match the source."""
    src, dst = ET.parse(source).getroot(), ET.parse(destination).getroot()
    if src.get("name") != dst.get("name"):
        raise AssertionError("robot name changed")
    movable = lambda root: [(j.get("name"), j.get("type")) for j in root.findall("joint") if j.get("type") != "fixed"]
    if movable(src) != movable(dst):
        raise AssertionError("movable joint list changed")
    src_joints = {j.get("name"): j for j in src.findall("joint")}
    dst_joints = {j.get("name"): j for j in dst.findall("joint")}
    if src_joints.keys() != dst_joints.keys():
        raise AssertionError("joint set changed")
    for name, a in src_joints.items():
        b = dst_joints[name]
        for child in a:
            other = b.find(child.tag)
            if child.tag == "origin" and name in FINGER_JOINTS:
                if child.get("xyz") != other.get("xyz"):
                    raise AssertionError(f"{name}: origin xyz changed")
                continue
            if ET.tostring(child) != ET.tostring(other):
                raise AssertionError(f"{name}: <{child.tag}> changed")
    src_links = {l.get("name"): ET.tostring(l) for l in src.findall("link")}
    dst_links = {l.get("name"): ET.tostring(l) for l in dst.findall("link")}
    if src_links != dst_links:
        raise AssertionError("link definitions changed")
